/**
 * Get translation for key in specified or current language
 */
function t(key, lang = null) {
  const currentLang = lang || getCurrentLanguage();
  const dict = I18N_STRINGS[currentLang] || I18N_STRINGS['en'];
  if (dict && dict[key] !== undefined) {
    return dict[key];
  }
  // Fallback to English
  if (I18N_STRINGS['en'] && I18N_STRINGS['en'][key] !== undefined) {
    return I18N_STRINGS['en'][key];
  }
  return key;
}

/**
 * Get current application language code
 */
function getCurrentLanguage() {
  return localStorage.getItem('phonemail_display_lang') || 
         localStorage.getItem('phonemail_audio_lang') || 
         'en';
}

/**
 * Set and persist application language, update all static DOM nodes,
 * and dispatch event to re-translate dynamic content (emails list & reading pane).
 */
function setAppLanguage(langCode) {
  if (!I18N_STRINGS[langCode]) {
    langCode = 'en';
  }

  localStorage.setItem('phonemail_display_lang', langCode);
  localStorage.setItem('phonemail_audio_lang', langCode);

  // Sync all select elements in header, toolbar, settings modal
  document.querySelectorAll('.app-lang-select, .audio-lang-select, #settings-display-lang, #settings-audio-lang').forEach(sel => {
    sel.value = langCode;
  });

  // Apply translations to all DOM elements with data-i18n attributes
  applyI18nToDOM(langCode);

  const langObj = I18N_LANGUAGES.find(l => l.code === langCode);
  const langName = langObj ? langObj.label : langCode;

  if (typeof showNotificationToast === 'function') {
    showNotificationToast(`Language: ${langName}`);
  }

  // Trigger app.js event for re-translating emails and reading pane
  if (window.onAppLanguageChanged && typeof window.onAppLanguageChanged === 'function') {
    window.onAppLanguageChanged(langCode);
  }
}

/**
 * Scan DOM and update all localized elements
 */
function applyI18nToDOM(langCode = null) {
  const lang = langCode || getCurrentLanguage();
  
  // 1. Text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const trans = t(key, lang);
    if (trans && trans !== key) {
      el.textContent = trans;
    }
  });

  // 2. Placeholders
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    const trans = t(key, lang);
    if (trans && trans !== key) {
      el.setAttribute('placeholder', trans);
    }
  });

  // 3. Titles / Tooltips
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.getAttribute('data-i18n-title');
    const trans = t(key, lang);
    if (trans && trans !== key) {
      el.setAttribute('title', trans);
    }
  });

  // 4. Update html lang attribute
  document.documentElement.setAttribute('lang', lang);
}

// Expose on window object
window.phoneMailI18n = {
  languages: I18N_LANGUAGES,
  strings: I18N_STRINGS,
  t,
  getCurrentLanguage,
  setAppLanguage,
  applyI18nToDOM
};
